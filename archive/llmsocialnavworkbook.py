def generate_adj_list(names, shuffle_adj_list=True, one_tok=False, use_symbolic_baseline=False):
  adj_list_suffix = 'adj-list-shuffled' if shuffle_adj_list else 'adj-list-ordered'

  # TWEAK: Logic to handle the new random-symbols suffix
  if use_symbolic_baseline:
    tok_suffix = 'random-symbols'
  else:
    tok_suffix = 'one-token-names' if one_tok else 'all-names'

  suffix = f'{adj_list_suffix}_{tok_suffix}'
  np.random.seed(42)

  all_adj_sentences = []
  all_id_to_names = []

  for _ in range(100):
    np.random.shuffle(names)
    selected_names = names[:13]

    # --- Graph Structure Definition ---
    # Mapping 1-13 (user input) to 0-12 (array indices)
    # Node 1 -> Index 0
    # Node 2 -> Index 1
    # ...
    # Node 13 -> Index 12

    adj = {
      0: [1, 7],           # 1 connects to 2, 8 (Indices: 1, 7)
      1: [0, 3, 2],        # 2 connects to 1, 4, 3 (Indices: 0, 3, 2)
      2: [1, 3, 4],        # 3 connects to 2, 4, 5 (Indices: 1, 3, 4)
      3: [1, 2, 4, 5],     # 4 connects to 2, 3, 5, 6 (Indices: 1, 2, 4, 5)
      4: [2, 3, 6],        # 5 connects to 3, 4, 7 (Indices: 2, 3, 6)
      5: [3, 6],           # 6 connects to 4, 7 (Indices: 3, 6)
      6: [4, 5],           # 7 connects to 5, 6 (Indices: 4, 5)
      7: [0, 8, 9],        # 8 connects to 1, 9, 10 (Indices: 0, 8, 9)
      8: [7, 10],          # 9 connects to 8, 11 (Indices: 7, 10)
      9: [7, 11],          # 10 connects to 8, 12 (Indices: 7, 11)
      10: [8, 11, 12],     # 11 connects to 9, 12, 13 (Indices: 8, 11, 12)
      11: [9, 10, 12],     # 12 connects to 10, 11, 13 (Indices: 9, 10, 12)
      12: [10, 11]         # 13 connects to 11, 12 (Indices: 10, 11)
    }

    # --- Generate Prompt String ---

    sentences = []
    # Iterate through nodes in order (0 to 12)
    for i in range(13):
      name_i = selected_names[i]
      # Get list of friends (neighbors) for this person
      neighbors = sorted(adj[i])

      for n_idx in neighbors:
        name_n = selected_names[n_idx]
        sentence = f"{name_i} is friends with {name_n}."
        sentences.append(sentence)

    if shuffle_adj_list:
      np.random.shuffle(sentences)

    all_adj_sentences.append(sentences)
    all_id_to_names.append(selected_names)

  adj_list = pd.DataFrame([all_adj_sentences, all_id_to_names]).T
  adj_list.to_csv(f'adj-list_{suffix}.csv', index=False)

  return adj_list

