def generate_questions(adj_list, tasks, shuffle_adj_list=True, one_tok=False,
                       shuffle_adj_prompts=False, shuffle_opts=True, use_symbolic_baseline=False):
  np.random.seed(42)

  adj_list_suffix = 'adj-list-shuffled' if shuffle_adj_list else 'adj-list-ordered'

  # TWEAK: Logic to handle the new random-symbols suffix
  if use_symbolic_baseline:
    tok_suffix = 'random-symbols'
  else:
    tok_suffix = 'one-token-names' if one_tok else 'all-names'

  adj_prompts_suffix = 'adj-prompt-shuffled' if shuffle_adj_prompts else 'adj-prompt-ordered'
  opts_suffix = 'choices-shuffled' if shuffle_opts else 'choices-ordered'
  suffix = f'{adj_list_suffix}_{tok_suffix}_{adj_prompts_suffix}_{opts_suffix}'

  questions = []
  startpoints = []
  endpoints = []
  opt1s = []
  opt2s = []
  correct_choices = []
  question_ids = []
  prompt_ids = []

  for i in range(len(adj_list)):
    curr_prompt, curr_names = adj_list.iloc[i, 0], adj_list.iloc[i, 1]

    for index, row in tasks.iterrows():
      temp_prompt = curr_prompt.copy()

      if shuffle_adj_prompts:
        np.random.shuffle(temp_prompt)
      temp_prompt = ' '.join(temp_prompt)

      name1 = curr_names[row['startpoint_id'] - 1]
      name2 = curr_names[row['endpoint_id'] - 1]
      name3 = curr_names[row['opt1_id'] - 1]
      name4 = curr_names[row['opt2_id'] - 1]
      correct_choice = curr_names[row['correct_choice'] - 1]

      name_opts = [name3, name4]

      if shuffle_opts:
        np.random.shuffle(name_opts)

      name3, name4 = name_opts

      question = f"{name1} wants to pass a message most efficiently to {name2}, should {name1} begin by passing the message on to {name3} or {name4}?"
      question = " ".join([temp_prompt, question])
      questions.append(question)

      startpoints.append(name1)
      endpoints.append(name2)
      opt1s.append(name3)
      opt2s.append(name4)
      correct_choices.append(correct_choice)

      question_ids.append(index)
      prompt_ids.append(i)

  all_questions = pd.DataFrame([questions, startpoints, endpoints, opt1s, opt2s, correct_choices, question_ids, prompt_ids]).T
  all_questions.columns = ["question", "startpoint", "endpoint", "opt1", "opt2", "correct_choice", "question_id", "prompt_id"]
  all_questions.to_csv(f'questions_{suffix}.csv', index=False)

  return all_questions

import random
import string

def generate_symbolic_names(count, length=5):
    """Generates a list of unique strings made of random symbols, letters, and digits."""
    # TWEAK: Added ascii_letters and digits to the character pool
    chars = "!@#$%^&*()-_=+[]{}|;:,.<>?" + string.ascii_letters + string.digits
    symbolic_names = set()

    while len(symbolic_names) < count:
        new_name = ''.join(random.choices(chars, k=length))
        symbolic_names.add(new_name)

    return list(symbolic_names)

