def filter_names_with_tokenizer(names, tokenizer=None, use_filter_tok=True, use_filter_sim=True):

    def filter_tok(names_list):
        # If tokenizer was never defined, use the length-based backup
        if tokenizer is None:
            print("Warning: No tokenizer found. Falling back to 4-letter limit.")
            return [n.strip() for n in names_list if 1 < len(n.strip()) <= 4]

        one_token_names = []
        for n in names_list:
            name_strip = n.strip()
            # The 'tokenizer' variable must exist for this line to work:
            tokens = tokenizer.encode(name_strip, add_special_tokens=False)
            if len(tokens) == 1:
                one_token_names.append(name_strip)
        return one_token_names

    def filter_sim(names_list):
        from difflib import SequenceMatcher
        def similar(a, b):
            return SequenceMatcher(None, a, b).ratio()

        filtered_list = []
        for n in names_list:
            exists = False
            for m in filtered_list:
                if similar(n, m) > 0.70:
                    exists = True
                    break
            if not exists:
                filtered_list.append(n)
        return filtered_list

    result = names
    if use_filter_tok:
        result = filter_tok(result)
    if use_filter_sim:
        result = filter_sim(result)

    return result

